package com.kmworks.kmreader.core.reader

import android.content.Context
import androidx.datastore.core.DataStore
import androidx.datastore.preferences.core.Preferences
import androidx.datastore.preferences.core.edit
import androidx.datastore.preferences.core.stringPreferencesKey
import androidx.datastore.preferences.preferencesDataStore
import dagger.hilt.android.qualifiers.ApplicationContext
import javax.inject.Inject
import javax.inject.Singleton
import kotlinx.coroutines.flow.Flow
import kotlinx.coroutines.flow.distinctUntilChanged
import kotlinx.coroutines.flow.map
import kotlinx.serialization.Serializable
import kotlinx.serialization.json.Json

private val Context.epubBookmarkDataStore: DataStore<Preferences> by preferencesDataStore(
    name = "epub_bookmarks",
)

/**
 * A reader bookmark: the position it was taken at, plus enough text to recognise it in a list.
 *
 * The position is stored twice on purpose. [chapterIndex] / [chapterFraction] is what a jump
 * restores (the reader lands on that chapter and scrolls to the fraction, the exact slot a link
 * jump uses), while [totalProgression] is only for the list readout — deriving one from the other
 * needs the chapter weights, and those are fetched off the first-render path and may be missing.
 *
 * Bookmarks are keyed by the Komga book DTO id ([bookDtoId] in [EpubBookmarkStore]), never by the
 * cache row id: Room here is a pure cache that a destructive fallback may drop.
 */
@Serializable
data class EpubBookmark(
    val id: String,
    val chapterIndex: Int,
    val chapterFraction: Float,
    val totalProgression: Float,
    /** Chapter title at bookmark time (falls back to the entry's position when the toc has none). */
    val chapterTitle: String,
    val createdAtMs: Long = 0L,
)

/**
 * EPUB bookmark persistence (pattern mirrors [EpubThemePresetStore]: dedicated DataStore file +
 * @Serializable payload + kotlinx.serialization JSON). One preferences key holds the bookmarks of
 * every book, keyed by book DTO id, so clearing one book never rewrites another book's list.
 */
@Singleton
class EpubBookmarkStore @Inject constructor(
    @ApplicationContext context: Context,
) {
    private val dataStore = context.epubBookmarkDataStore
    private val json = Json { ignoreUnknownKeys = true }
    private val key = stringPreferencesKey("bookmarks_by_book_json")

    /** Bookmarks of one book, in reading order (chapter first, then position inside it). */
    fun bookmarks(bookDtoId: String): Flow<List<EpubBookmark>> = dataStore.data
        .map { prefs -> decode(prefs[key])[bookDtoId].orEmpty() }
        .distinctUntilChanged()

    /** Insert or replace one bookmark (ids are generated by the caller). */
    suspend fun save(bookDtoId: String, bookmark: EpubBookmark) {
        update(bookDtoId) { current ->
            (current.filterNot { it.id == bookmark.id } + bookmark).sortedWith(READING_ORDER)
        }
    }

    suspend fun delete(bookDtoId: String, bookmarkId: String) {
        update(bookDtoId) { current -> current.filterNot { it.id == bookmarkId } }
    }

    private suspend fun update(bookDtoId: String, transform: (List<EpubBookmark>) -> List<EpubBookmark>) {
        dataStore.edit { prefs ->
            val all = decode(prefs[key])
            val next = transform(all[bookDtoId].orEmpty())
            prefs[key] = json.encodeToString(
                if (next.isEmpty()) all - bookDtoId else all + (bookDtoId to next),
            )
        }
    }

    private fun decode(raw: String?): Map<String, List<EpubBookmark>> =
        raw?.let {
            runCatching { json.decodeFromString<Map<String, List<EpubBookmark>>>(it) }
                .getOrDefault(emptyMap())
        } ?: emptyMap()

    private companion object {
        val READING_ORDER: Comparator<EpubBookmark> =
            compareBy({ it.chapterIndex }, { it.chapterFraction })
    }
}
